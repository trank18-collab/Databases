-- Create a playlist
INSERT INTO PLAYLIST
    (PLAYLIST_ID, PLAYLIST_NAME, MOVIE_ID, MUSIC_GENRE)
VALUES
    (PLAYLIST_SEQ.NEXTVAL, '&playlist_name', &movie_id, '&music_genre');

-- Add matching songs to the playlist
INSERT INTO PLAYLIST_SONG
    (PLAYLIST_ID, SONG_ID, TRACK_NUMBER)
SELECT
    PLAYLIST_SEQ.CURRVAL,
    MUSIC.SONG_ID,
    ROW_NUMBER() OVER (
        ORDER BY MUSIC.SONG_TITLE, MUSIC.SONG_ID
    )
FROM MUSIC
WHERE MUSIC.MOVIE_ID = &movie_id
  AND MUSIC.GENRE = '&music_genre';

COMMIT;

-- Display playlist information
SELECT
    PLAYLIST.PLAYLIST_ID,
    PLAYLIST.PLAYLIST_NAME,
    MOVIE.MOVIE_TITLE,
    PLAYLIST.MUSIC_GENRE,
    PLAYLIST.CREATED_DATE
FROM PLAYLIST
JOIN MOVIE
    ON PLAYLIST.MOVIE_ID = MOVIE.MOVIE_ID
WHERE PLAYLIST.PLAYLIST_ID = PLAYLIST_SEQ.CURRVAL;

-- Display the songs in the playlist
SELECT
    PLAYLIST_SONG.TRACK_NUMBER,
    PLAYLIST.PLAYLIST_NAME,
    MUSIC.SONG_TITLE,
    MUSIC.ARTIST_NAME,
    MOOD.MOOD_NAME
FROM PLAYLIST
JOIN PLAYLIST_SONG
    ON PLAYLIST.PLAYLIST_ID = PLAYLIST_SONG.PLAYLIST_ID
JOIN MUSIC
    ON PLAYLIST_SONG.SONG_ID = MUSIC.SONG_ID
JOIN MOOD
    ON MUSIC.MOOD_ID = MOOD.MOOD_ID
WHERE PLAYLIST.PLAYLIST_ID = PLAYLIST_SEQ.CURRVAL
ORDER BY PLAYLIST_SONG.TRACK_NUMBER;


