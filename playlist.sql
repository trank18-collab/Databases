-- Create a playlist
INSERT INTO PLAYLIST
    (PLAYLIST_ID, PLAYLIST_NAME, MOVIE_ID, MUSIC_GENRE_ID)
VALUES
    (PLAYLIST_SEQ.NEXTVAL, '&playlist_name', &movie_id, &music_genre_id);

-- Add matching songs to the playlist
INSERT INTO PLAYLIST_SONG
    (PLAYLIST_ID, SONG_ID)
SELECT
    PLAYLIST_SEQ.CURRVAL,
    MUSIC.SONG_ID
FROM MUSIC
JOIN MOVIE_GENRE
    ON MUSIC.MOOD_ID = MOVIE_GENRE.MOOD_ID
JOIN MOVIE_MOVIE_GENRE
    ON MOVIE_GENRE.MOVIE_GENRE_ID =
       MOVIE_MOVIE_GENRE.MOVIE_GENRE_ID
WHERE MUSIC.MUSIC_GENRE_ID = &music_genre_id
  AND MOVIE_MOVIE_GENRE.MOVIE_ID = &movie_id;

COMMIT;

-- Display playlist information
SELECT
    PLAYLIST.PLAYLIST_ID,
    PLAYLIST.PLAYLIST_NAME,
    MOVIE.MOVIE_TITLE,
    MUSIC_GENRE.GENRE_NAME AS MUSIC_GENRE,
    PLAYLIST.CREATED_DATE
FROM PLAYLIST
JOIN MOVIE
    ON PLAYLIST.MOVIE_ID = MOVIE.MOVIE_ID
JOIN MUSIC_GENRE
    ON PLAYLIST.MUSIC_GENRE_ID = MUSIC_GENRE.MUSIC_GENRE_ID
WHERE PLAYLIST.PLAYLIST_ID = PLAYLIST_SEQ.CURRVAL;

-- Display the songs in the playlist
SELECT
    PLAYLIST.PLAYLIST_NAME,
    MUSIC.SONG_TITLE,
    MUSIC.ARTIST_NAME,
    MOOD.MOOD_NAME
FROM PLAYLIST
JOIN PLAYLIST_SONG
    ON PLAYLIST.PLAYLIST_ID = PLAYLIST_SONG.PLAYLIST_ID
JOIN MUSIC
    ON PLAYLIST_SONG.SONG_ID = MUSIC.SONG_ID
JOIN MOOD
    ON MUSIC.MOOD_ID = MOOD.MOOD_ID
WHERE PLAYLIST.PLAYLIST_ID = PLAYLIST_SEQ.CURRVAL
ORDER BY MUSIC.SONG_TITLE;


